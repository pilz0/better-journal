package foo.pilz.freaklog.data.room

import androidx.room.Room
import androidx.room.testing.MigrationTestHelper
import androidx.sqlite.db.framework.FrameworkSQLiteOpenHelperFactory
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Room database migration tests.
 *
 * Every migration registered in [AppDatabase] should be exercised here:
 *
 *   1. We create a database at the source schema version.
 *   2. We close it and re-open it at the target version, asking Room to apply
 *      every registered migration.
 *   3. We then validate the database is openable through the normal Room
 *      builder (which runs `validateMigration` on every entity).
 *
 * If a future contributor adds an `AutoMigration` they are responsible for
 * adding the corresponding `from -> to` pair in [migrationPairs] below.
 *
 * Note: schema version 13 was skipped (the migration jumps 12 -> 14), so any
 * pair containing 13 is intentionally absent.
 */
@RunWith(AndroidJUnit4::class)
class AppDatabaseMigrationTest {

    @get:Rule
    val helper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(),
        AppDatabase::class.java,
    )

    @Test
    fun migrate_individual_pairs_succeeds_for_every_registered_auto_migration() {
        for ((from, to) in migrationPairs) {
            // Create the DB at the older schema version.
            helper.createDatabase(TEST_DB, from).apply { close() }

            // Re-open it at the target version. `validateDroppedTables = true`
            // catches accidental drops in autogenerated SQL.
            helper.runMigrationsAndValidate(
                TEST_DB,
                to,
                /* validateDroppedTables = */ true,
                AppDatabase.MIGRATION_21_22,
            ).close()
        }
    }

    @Test
    fun migrate_all_the_way_from_v1_to_latest_succeeds() {
        helper.createDatabase(TEST_DB, 1).apply { close() }
        helper.runMigrationsAndValidate(
            TEST_DB,
            AppDatabase.LATEST_SCHEMA_VERSION,
            /* validateDroppedTables = */ true,
            AppDatabase.MIGRATION_21_22,
        ).close()
    }

    @Test
    fun migrate_from_oldest_yields_same_schema_as_fresh_database() {
        // Migrate from v1.
        helper.createDatabase(TEST_DB, 1).apply { close() }
        helper.runMigrationsAndValidate(
            TEST_DB,
            AppDatabase.LATEST_SCHEMA_VERSION,
            /* validateDroppedTables = */ true,
            AppDatabase.MIGRATION_21_22,
        ).close()

        // Now actually open the migrated database via Room. Room will run its
        // own `validateMigration` against the entity metadata; if anything is
        // mis-aligned (column type, index, FK) this throws.
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val db = Room.databaseBuilder(context, AppDatabase::class.java, TEST_DB)
            .addMigrations(AppDatabase.MIGRATION_21_22)
            .openHelperFactory(FrameworkSQLiteOpenHelperFactory())
            .build()
        try {
            // Touch a table to force the database to be opened/validated.
            val cursor = db.openHelper.writableDatabase.query("SELECT 1")
            assertNotNull(cursor)
            cursor.close()
            // Sanity-check the user_version pragma to verify we landed on the
            // expected schema version.
            val versionCursor = db.openHelper.writableDatabase.query("PRAGMA user_version")
            versionCursor.use {
                check(it.moveToFirst())
                assertEquals(AppDatabase.LATEST_SCHEMA_VERSION, it.getInt(0))
            }
        } finally {
            db.close()
        }
    }

    @Test
    fun migrate_v21_to_v22_creates_change_log_table_and_triggers() {
        helper.createDatabase(TEST_DB, 21).apply { close() }
        val db = helper.runMigrationsAndValidate(
            TEST_DB,
            22,
            /* validateDroppedTables = */ true,
            AppDatabase.MIGRATION_21_22,
        )

        // Verify the ingestion_change_log table exists.
        val tableCursor = db.query(
            "SELECT name FROM sqlite_master WHERE type='table' AND name='ingestion_change_log'"
        )
        tableCursor.use {
            check(it.moveToFirst()) { "Expected ingestion_change_log table to exist" }
        }

        // Verify ingestion triggers exist (INSERT, UPDATE, DELETE).
        val triggerCursor = db.query(
            "SELECT name FROM sqlite_master WHERE type='trigger' AND tbl_name='Ingestion'"
        )
        triggerCursor.use {
            check(it.count == 3) { "Expected 3 triggers on Ingestion table, got ${it.count}" }
        }

        // Verify the cap trigger exists.
        val capCursor = db.query(
            "SELECT name FROM sqlite_master WHERE type='trigger' AND name='ingestion_change_log_cap'"
        )
        capCursor.use {
            check(it.moveToFirst()) { "Expected ingestion_change_log_cap trigger to exist" }
        }

        // Verify an INSERT trigger fires by inserting a test row.
        db.execSQL("INSERT INTO Experience (title, text, creationDate, sortDate, isFavorite) VALUES ('test', '', 0, 0, 0)")
        db.execSQL("INSERT INTO Ingestion (substanceName, time, administrationRoute, dose, isDoseAnEstimate, experienceId) VALUES ('Test', 0, 'ORAL', 1.0, 0, last_insert_rowid())")
        val logCursor = db.query("SELECT * FROM ingestion_change_log WHERE op = 'INSERT'")
        logCursor.use {
            check(it.moveToFirst()) { "Expected INSERT trigger to log a row" }
            assertEquals("INSERT", it.getString(it.getColumnIndexOrThrow("op")))
        }

        db.close()
    }

    @Test
    fun migrate_v16_reminder_preserves_legacy_interval_and_user_fields() {
        helper.createDatabase(TEST_DB, 16).use { db ->
            db.execSQL(
                "INSERT INTO reminder (id, title, hour, minute, isEnabled, intervalValue, intervalUnit)" +
                    " VALUES (42, 'Legacy reminder', 9, 15, 1, 6, 'HOURS')"
            )
        }
        helper.runMigrationsAndValidate(
            TEST_DB, AppDatabase.LATEST_SCHEMA_VERSION, true, AppDatabase.MIGRATION_21_22,
        ).use { db ->
            db.query("SELECT * FROM reminder WHERE id = 42").use { cursor ->
                check(cursor.moveToFirst())
                assertEquals("Legacy reminder", cursor.getString(cursor.getColumnIndexOrThrow("title")))
                assertEquals("INTERVAL", cursor.getString(cursor.getColumnIndexOrThrow("scheduleType")))
                assertEquals(9, cursor.getInt(cursor.getColumnIndexOrThrow("hour")))
                assertEquals(15, cursor.getInt(cursor.getColumnIndexOrThrow("minute")))
                assertEquals(1, cursor.getInt(cursor.getColumnIndexOrThrow("isEnabled")))
                assertEquals(6, cursor.getInt(cursor.getColumnIndexOrThrow("intervalValue")))
                assertEquals("HOURS", cursor.getString(cursor.getColumnIndexOrThrow("intervalUnit")))
            }
        }
    }

    @Test
    fun change_log_records_update_delete_and_keeps_only_latest_thousand_events() {
        helper.createDatabase(TEST_DB, 21).close()
        helper.runMigrationsAndValidate(TEST_DB, 22, true, AppDatabase.MIGRATION_21_22).use { db ->
            db.execSQL("INSERT INTO Experience (id, title, text, creationDate, sortDate, isFavorite) VALUES (1, 'test', '', 0, 0, 0)")
            db.execSQL(
                "INSERT INTO Ingestion (id, substanceName, time, administrationRoute, dose, isDoseAnEstimate, experienceId)" +
                    " VALUES (7, 'Test', 0, 'ORAL', 1.0, 0, 1)"
            )
            db.execSQL("UPDATE Ingestion SET dose = 2.0 WHERE id = 7")
            db.execSQL("DELETE FROM Ingestion WHERE id = 7")
            db.query("SELECT ingestion_id, op FROM ingestion_change_log ORDER BY seq").use { cursor ->
                for (op in listOf("INSERT", "UPDATE", "DELETE")) {
                    check(cursor.moveToNext())
                    assertEquals(7, cursor.getInt(0))
                    assertEquals(op, cursor.getString(1))
                }
                assertEquals(3, cursor.count)
            }

            db.beginTransaction()
            try {
                repeat(1005) {
                    db.execSQL(
                        "INSERT INTO ingestion_change_log (ingestion_id, op, changed_at) VALUES (?, 'INSERT', 0)",
                        arrayOf<Any>(it),
                    )
                }
                db.setTransactionSuccessful()
            } finally {
                db.endTransaction()
            }
            db.query("SELECT COUNT(*), MIN(ingestion_id), MAX(ingestion_id) FROM ingestion_change_log").use { cursor ->
                check(cursor.moveToFirst())
                assertEquals(1000, cursor.getInt(0))
                assertEquals(5, cursor.getInt(1))
                assertEquals(1004, cursor.getInt(2))
            }
        }
    }

    companion object {
        private const val TEST_DB = "migration-test.db"

        /**
         * Every consecutive pair of schema versions with a registered migration.
         * Keep in sync with both the auto-migration list and the manual
         * [AppDatabase.MIGRATION_21_22] step.
         *
         * Schema 13 was skipped, hence the (12, 14) pair.
         */
        private val migrationPairs: List<Pair<Int, Int>> = listOf(
            1 to 2,
            2 to 3,
            3 to 4,
            4 to 5,
            5 to 6,
            6 to 7,
            7 to 8,
            8 to 9,
            9 to 10,
            10 to 11,
            11 to 12,
            12 to 14,
            14 to 15,
            15 to 16,
            16 to 17,
            17 to 18,
            18 to 19,
            19 to 20,
            20 to 21,
            21 to 22,
            22 to 23,
            23 to 24,
            24 to 25,
            25 to 26,
            26 to 27,
            27 to 28,
            28 to 29,
        )
    }
}
